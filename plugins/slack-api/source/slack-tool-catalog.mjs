const text = (maximum = 300) => ({ type: "string", minLength: 1, maxLength: maximum });
const id = (pattern) => ({ ...text(80), pattern });
const channel = id("^[CDG][A-Z0-9]+$");
const user = id("^[UW][A-Z0-9]+$");
const file = id("^F[A-Z0-9]+$");
const timestamp = { ...text(32), pattern: "^[0-9]{1,20}\\.[0-9]{1,10}$" };
const boolean = { type: "boolean" };
const integer = (maximum) => ({ type: "integer", minimum: 1, maximum });
const choice = (...values) => ({ type: "string", enum: values });
const array = (items, maximum = 50) => ({ type: "array", items, minItems: 1, maxItems: maximum });
const object = (properties, required = []) => ({
  type: "object",
  properties,
  required,
  additionalProperties: false,
});
const page = { limit: integer(100), cursor: text(2048) };
const history = {
  channel_id: channel,
  limit: integer(15),
  cursor: text(2048),
  oldest: timestamp,
  latest: timestamp,
  inclusive: boolean,
};
const message = { channel_id: channel, message: text(40000), thread_ts: timestamp };
const listCell = object(
  {
    column_id: text(80),
    text: text(10000),
    number: { type: "number" },
    checkbox: boolean,
    date: array({ ...text(10), pattern: "^[0-9]{4}-[0-9]{2}-[0-9]{2}$" }, 10),
    user: array(user, 20),
    select: array(text(100), 20),
  },
  ["column_id"],
);
const listColumns = array(
  object(
    {
      key: text(80),
      name: text(100),
      type: choice("text", "number", "checkbox", "date", "user", "email", "phone", "link"),
      is_primary_column: boolean,
    },
    ["key", "name", "type"],
  ),
  30,
);

// Fixed method and field maps are executable authority: tool inputs cannot select a URL or token.
const tool = (
  name,
  method,
  description,
  properties,
  required,
  scopes,
  resultKeys,
  options = {},
) => ({
  name,
  method,
  description,
  inputSchema: object(properties, required),
  scopes,
  resultKeys,
  classification: "read",
  ...options,
});

